package cn.homeledger.controller;

import static org.assertj.core.api.Assertions.assertThat;

import java.time.LocalDate;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpStatus;

import cn.homeledger.config.TimeConfig;
import cn.homeledger.support.ApiTestBase;
import tools.jackson.databind.JsonNode;

/**
 * §4.6 的首页聚合（{@code GET /home/overview}）。
 * <p>
 * 这一条端点的价值是「一次请求」与「不产生第二套口径」，所以断言分两处落：数字与它本来的端点一致
 * （本月收支对 {@code /transactions/summary}），以及最近动态的<b>过滤</b>——关掉猫咪模块后
 * 首页就不该再出猫咪条目（验收用例 31 的后半句）。
 */
class HomeOverviewIntegrationTest extends ApiTestBase {

	private static final String PHONE_A = "13800000001";

	private static final String PHONE_OTHER = "13800000003";

	private static final String PHONE_ALONE = "13800000004";

	private static final String FINANCE = "FINANCE";

	private static final String CAT = "CAT";

	private static final String BABY = "BABY";

	private static final LocalDate TODAY = LocalDate.now(TimeConfig.ZONE);

	@Test
	@DisplayName("概要：本月收支结余取当月 1 日到今天，一笔都没有时是 0 而不是空")
	void summaryCoversTheCurrentMonth() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");
		record(owner, "EXPENSE", "120.00", TODAY);
		record(owner, "INCOME", "5000.00", TODAY);

		JsonNode summary = overview(owner).path("summary");

		assertThat(summary.path("monthExpense").asText()).isEqualTo("120.00");
		assertThat(summary.path("monthIncome").asText()).isEqualTo("5000.00");
		assertThat(summary.path("monthBalance").asText()).isEqualTo("4880.00");
	}

	@Test
	@DisplayName("当月已记录天数按自然日去重：一天记三笔只算一天")
	void recordedDaysCountsDistinctDays() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");
		record(owner, "EXPENSE", "10.00", TODAY);
		record(owner, "EXPENSE", "20.00", TODAY);
		record(owner, "EXPENSE", "30.00", TODAY);
		record(owner, "EXPENSE", "40.00", TODAY.minusDays(1));
		// 今天是 1 号时「昨天」落进上个月，那样期望值就是 1——不写死 2，按实际落在本月里的天数算
		long inThisMonth = List.of(TODAY, TODAY, TODAY, TODAY.minusDays(1))
			.stream()
			.filter(day -> !day.isBefore(TODAY.withDayOfMonth(1)))
			.distinct()
			.count();

		assertThat(overview(owner).path("summary").path("recordedDays").asInt())
			.as("这一格说的是「记了几天账」，不是「记了几笔」").isEqualTo((int) inThisMonth);
	}

	@Test
	@DisplayName("上个月的流水不进本月概要")
	void lastMonthIsNotInThisMonthSummary() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");
		record(owner, "EXPENSE", "999.00", TODAY.minusMonths(1).withDayOfMonth(1));

		assertThat(overview(owner).path("summary").path("monthExpense").asText()).as("金额一律两位小数，空集也是 0.00")
			.isEqualTo("0.00");
	}

	@Test
	@DisplayName("今日自动生成笔数：建规则的当场生成的那一笔当天就算进来")
	void autoGeneratedTodayCountsRuleGeneratedRows() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");

		Map<String, Object> payload = new LinkedHashMap<>();
		payload.put("name", "每天一笔");
		payload.put("amount", "10.00");
		payload.put("categoryId", topCategoryId(owner, "餐饮"));
		payload.put("accountId", paymentAccountId(owner, "现金"));
		payload.put("periodType", "DAILY");
		payload.put("periodValue", Map.of("intervalDays", 1));
		payload.put("startDate", TODAY.toString());
		assertThat(postJson(RECURRING_RULES, payload, owner.accessToken()).code()).isEqualTo("OK");

		assertThat(overview(owner).path("summary").path("autoGeneratedToday").asInt()).isEqualTo(1);
	}

	@Test
	@DisplayName("预算给全量三个维度：首页要判「任一维度超支就整卡变红」，只给家庭那条判不出来")
	void budgetsIncludeEveryDimension() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");
		Map<String, Object> family = budget("FAMILY", null, "5000.00");
		Map<String, Object> category = budget("CATEGORY", topCategoryId(owner, "餐饮"), "800.00");
		assertThat(putJson(BUDGETS, Map.of("items", List.of(family, category)), owner.accessToken()).code())
			.isEqualTo("OK");

		List<JsonNode> budgets = toList(overview(owner).path("budgets"));
		assertThat(budgets.stream().map(row -> row.path("scope").asText()).toList())
			.containsExactlyInAnyOrder("FAMILY", "CATEGORY");
	}

	@Test
	@DisplayName("最近动态跨模块混合，按写入时刻倒序，最多 5 条")
	void recentActivitiesMixModulesNewestFirst() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");
		String token = owner.accessToken();
		record(owner, "EXPENSE", "12.00", TODAY);
		long catId = cat(owner, "咪咪");
		assertThat(postJson(CAT_DEWORMINGS, Map.of("catId", catId, "type", "EXTERNAL", "doneDate", TODAY.toString(),
				"medicine", "测试用药"), token).code()).isEqualTo("OK");
		long babyId = createBaby(token, "小满", "MALE", TODAY.minusDays(30).toString());
		createGrowth(token, babyId, TODAY.toString(), "70.0", "8.00");

		List<JsonNode> rows = toList(overview(owner).path("recentActivities"));

		assertThat(rows).as("三条记录，跨三个模块").hasSize(3);
		assertThat(rows.stream().map(row -> row.path("module").asText()).distinct().toList())
			.containsExactlyInAnyOrder(FINANCE, CAT, BABY);
		assertThat(rows.stream().map(row -> row.path("type").asText()).toList())
			.contains(RecentTypes.TRANSACTION, RecentTypes.CAT_DEWORMING, RecentTypes.BABY_GROWTH);
		// 写入时刻倒序：最后写的排最前
		assertThat(rows.get(0).path("occurredAt").asText())
			.isGreaterThanOrEqualTo(rows.get(rows.size() - 1).path("occurredAt").asText());
		assertThat(rows.get(0).path("actorName").asText()).as("记录人是昵称，不是 id").isEqualTo("张三");
	}

	@Test
	@DisplayName("只保留最近 5 条：第 6 新及更早的都不出现")
	void recentActivitiesAreCappedAtFive() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");
		for (int i = 0; i < 7; i++) {
			record(owner, "EXPENSE", (10 + i) + ".00", TODAY);
		}

		assertThat(toList(overview(owner).path("recentActivities"))).hasSize(5);
	}

	@Test
	@DisplayName("验收用例 31 后半句：关掉猫咪模块后最近动态不再出现猫咪条目")
	void recentActivitiesHonourModuleSwitches() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");
		record(owner, "EXPENSE", "12.00", TODAY);
		long catId = cat(owner, "咪咪");
		assertThat(postJson(CAT_DEWORMINGS, Map.of("catId", catId, "type", "INTERNAL", "doneDate", TODAY.toString(),
				"medicine", "测试用药"), owner.accessToken()).code()).isEqualTo("OK");
		assertThat(recentTypes(owner)).as("先确认关掉之前两条都在")
			.containsExactlyInAnyOrder(RecentTypes.TRANSACTION, RecentTypes.CAT_DEWORMING);

		assertThat(putJson(PREFERENCE_MODULES, Map.of("items", List.of(pref(CAT, false))), owner.accessToken())
			.code()).isEqualTo("OK");

		List<JsonNode> rows = toList(overview(owner).path("recentActivities"));
		assertThat(rows.stream().map(row -> row.path("type").asText()).toList())
			.containsExactly(RecentTypes.TRANSACTION);
	}

	@Test
	@DisplayName("另一个家庭的动态与数字都不出现")
	void otherFamilyIsInvisible() throws Exception {
		Account owner = registerWithFamily(PHONE_A, "张三");
		Account outsider = registerWithFamily(PHONE_OTHER, "王五");
		record(owner, "EXPENSE", "120.00", TODAY);

		JsonNode theirs = overview(outsider);
		assertThat(theirs.path("summary").path("monthExpense").asText()).isEqualTo("0.00");
		assertThat(toList(theirs.path("recentActivities"))).isEmpty();
	}

	@Test
	@DisplayName("无家庭的账号：403，而不是一个全零的首页")
	void noFamilyIsForbidden() throws Exception {
		Account lonely = register(PHONE_ALONE, "赵六");

		assertThat(getJson(HOME_OVERVIEW, lonely.accessToken()).status()).isEqualTo(HttpStatus.FORBIDDEN.value());
	}

	// ---- 辅助 ----

	/** 最近动态的七类。测试里按名字断言，避免与服务端枚举耦合到「拼错也不报错」的程度。 */
	private static final class RecentTypes {

		private static final String TRANSACTION = "TRANSACTION";

		private static final String CAT_DEWORMING = "CAT_DEWORMING";

		private static final String BABY_GROWTH = "BABY_GROWTH";

		private RecentTypes() {
		}

	}

	private JsonNode overview(Account account) throws Exception {
		Call call = getJson(HOME_OVERVIEW, account.accessToken());
		assertThat(call.code()).isEqualTo("OK");
		return call.data();
	}

	private List<String> recentTypes(Account account) throws Exception {
		return toList(overview(account).path("recentActivities")).stream()
			.map(row -> row.path("type").asText())
			.toList();
	}

	private static Map<String, Object> pref(String moduleKey, boolean enabled) {
		Map<String, Object> item = new LinkedHashMap<>();
		item.put("moduleKey", moduleKey);
		item.put("enabled", enabled);
		return item;
	}

	private static Map<String, Object> budget(String scope, Long categoryId, String amount) {
		Map<String, Object> item = new LinkedHashMap<>();
		item.put("scope", scope);
		item.put("categoryId", categoryId);
		item.put("memberUserId", null);
		item.put("amount", amount);
		return item;
	}

	private void record(Account account, String type, String amount, LocalDate bizDate) throws Exception {
		Map<String, Object> body = new LinkedHashMap<>();
		body.put("amount", amount);
		body.put("categoryId", categoryId(account, type, "EXPENSE".equals(type) ? "餐饮" : "工资"));
		body.put("accountId", paymentAccountId(account, "现金"));
		body.put("bizDate", bizDate.toString());
		assertThat(postJson(TRANSACTIONS, body, account.accessToken()).code()).as("记一笔 %s %s", type, amount)
			.isEqualTo("OK");
	}

	/**
	 * 按名字取预置大类。基类的 {@code topCategoryId} 把查询写死成 EXPENSE，收入侧取不到，
	 * 而这里两档都要用到。
	 */
	private long categoryId(Account account, String type, String name) throws Exception {
		Call call = getJson(CATEGORIES, Map.of("type", type, "enabledOnly", "false"), account.accessToken());
		assertThat(call.code()).isEqualTo("OK");
		for (JsonNode node : call.data()) {
			if (node.path("name").asText().equals(name)) {
				return node.path("id").asLong();
			}
		}
		throw new AssertionError("预置类别树里应有 " + type + " 大类 " + name);
	}

	private long cat(Account account, String name) throws Exception {
		Call call = postJson(CATS, Map.of("name", name, "gender", "UNKNOWN", "birthdayEstimated", false, "neutered",
				"UNKNOWN"), account.accessToken());
		assertThat(call.code()).as("建档 %s", name).isEqualTo("OK");
		return call.data().path("id").asLong();
	}

	private static List<JsonNode> toList(JsonNode array) {
		List<JsonNode> nodes = new ArrayList<>();
		array.forEach(nodes::add);
		return nodes;
	}

}
