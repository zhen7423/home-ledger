package cn.homeledger.vo;

import java.math.BigDecimal;
import java.time.LocalDateTime;
import java.util.List;

import com.fasterxml.jackson.annotation.JsonFormat;

/**
 * §4.6 首页的聚合数据（§8 的 {@code GET /home/overview}）。
 * <p>
 * 一次请求把首页要的三份数据给全：概要、预算、最近动态。**待办提醒不在这里**——那份数据由
 * {@code GET /reminders/pending} 出，首页的卡片区与红点读同一份，因为「今天已经划掉」是设备级状态，
 * 只有客户端手里那份列表才滤得掉（服务端再返一份就会多出第二套口径）。
 * <p>
 * 家庭名称与成员列表也不在这里：那是 {@code GET /families/current} 的事，首页本来就有一份，
 * 同一个事实发两条端点只会让「改名之后首页还显示旧名」这种 bug 有地方藏。
 *
 * @param budgets 家庭全部维度的预算进度，原样转自 {@code BudgetService.progress}。给全量而不是只给家庭那一条：
 *        首页的预算卡要「家庭维度一条进度条 + 任一维度超支就整卡变红」，只给一条就判不出后面那半句
 */
public record HomeOverviewResponse(HomeSummary summary, List<BudgetProgressResponse> budgets,
		List<RecentActivityResponse> recentActivities) {

	/**
	 * §4.6 第 1、2 条与本轮之前的 S4 两块卡。
	 *
	 * @param recordedDays 当月有记录的天数。同一天记多笔只算一天——这一格说的是「这个月记了几天账」，
	 *        不是「记了几笔」，笔数在概要卡与流水列表里都有
	 * @param autoGeneratedToday 今天由周期规则自动生成的笔数（S4 那块「核对一下」的卡）。判据与流水列表
	 *        的 {@code source=AUTO} 筛选逐字相同：{@code rule_id} 有没有值
	 */
	public record HomeSummary(@JsonFormat(shape = JsonFormat.Shape.STRING) BigDecimal monthIncome,
			@JsonFormat(shape = JsonFormat.Shape.STRING) BigDecimal monthExpense,
			@JsonFormat(shape = JsonFormat.Shape.STRING) BigDecimal monthBalance, int recordedDays,
			int autoGeneratedToday) {

	}

	/**
	 * 一条最近动态（§4.6 第 6 条）。
	 *
	 * @param module 属于哪个模块（{@code ModuleKey} 枚举名），客户端按它挑图标、也按它过滤
	 * @param type 具体是哪一类记录（{@code RecentActivityType} 枚举名）。模块图标之外还要区分时用它，
	 *        目前界面不显示，但「六类记录挤在一个模块里」这件事在响应里说清楚，排查时少一次猜
	 * @param title 摘要的主句，如「记了一笔支出」「给咪咪做了外驱」
	 * @param summary 补充说明，如「餐饮 · 120.00 元」。与 title 分开是因为卡片一行放不下两件事，
	 *        而「谁做了什么」与「具体多少」在版式上是两行
	 * @param actorName 记录人昵称。取自己在册名单里查出的昵称（不是快照列——这六张表都没有快照列），
	 *        成员退出后名字会回落为 null，客户端显示「已退出的成员」
	 * @param occurredAt 记录写入时刻，客户端按它显示相对时间。排序也用它
	 * @param route 点进去落到哪一页，由服务端给，理由同 {@code PendingReminderResponse.route}
	 */
	public record RecentActivityResponse(String module, String type, String title, String summary, String actorName,
			@JsonFormat(shape = JsonFormat.Shape.STRING) LocalDateTime occurredAt, String route) {

	}

}
