import 'package:freezed_annotation/freezed_annotation.dart';

import 'budget_progress.dart';

part 'home_overview.freezed.dart';
part 'home_overview.g.dart';

/// §4.6 首页的聚合数据，对应后端的 HomeOverviewResponse。
///
/// **待办提醒不在这里**：那份数据走 `PendingReminderViewModel`（`GET /reminders/pending`），
/// 因为「今天已经划掉」是设备级状态，只有客户端手里那份列表滤得掉——服务端再返一份，
/// 首页就会出现「红点说 0 条、卡片区还挂着一条」这种自相矛盾。
@freezed
abstract class HomeOverview with _$HomeOverview {
  const factory HomeOverview({
    required HomeSummary summary,
    required List<BudgetProgress> budgets,
    required List<RecentActivity> recentActivities,
  }) = _HomeOverview;

  factory HomeOverview.fromJson(Map<String, dynamic> json) =>
      _$HomeOverviewFromJson(json);
}

/// 首页概要卡与家庭信息条要的五个数。金额是字符串（§4.2.1），前端只做显示格式化。
///
/// `recordedDays` 是「这个月记了几天账」而不是笔数：同一天记三笔算一天。
@freezed
abstract class HomeSummary with _$HomeSummary {
  const factory HomeSummary({
    required String monthIncome,
    required String monthExpense,
    required String monthBalance,
    required int recordedDays,
    required int autoGeneratedToday,
  }) = _HomeSummary;

  factory HomeSummary.fromJson(Map<String, dynamic> json) =>
      _$HomeSummaryFromJson(json);
}

/// 最近动态的一条（§4.6 第 6 条）。
///
/// `module` 决定卡片上的模块图标与配色，`type` 是更细的记录类别（目前不显示，留着给以后）；
/// `actorName` 为空表示记录人已经退出家庭（那六张表没有昵称快照，只有流水有），界面显示「已退出的成员」。
/// 相对时间由前端按 `occurredAt` 现算，服务端不下发「3 分钟前」这种会过期的字符串。
@freezed
abstract class RecentActivity with _$RecentActivity {
  const factory RecentActivity({
    required String module,
    required String type,
    required String title,
    required String summary,
    String? actorName,
    required DateTime occurredAt,
    required String route,
  }) = _RecentActivity;

  factory RecentActivity.fromJson(Map<String, dynamic> json) =>
      _$RecentActivityFromJson(json);
}
