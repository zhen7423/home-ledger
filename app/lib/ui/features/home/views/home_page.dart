/// §4.6 第 3 条：家庭总预算那一条进度。任一维度超支就整卡变红。
class _BudgetCard extends StatelessWidget {
  const _BudgetCard({required this.row, required this.anyExceeded});

  final BudgetProgress row;

  final bool anyExceeded;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    // 整卡变红看「任一维度超支」，这一条进度条上色看它自己的档位——两者可以不同：
    // 家庭维度 60%、某个类别超了，卡的底色是红的，条还是正常色
    final color = anyExceeded
        ? theme.colorScheme.error
        : budgetLevelColor(theme.colorScheme, row.level);
    final remainingCents = toCents(row.remaining);

    return Card(
      margin: const EdgeInsets.fromLTRB(16, 6, 16, 6),
      color: anyExceeded ? theme.colorScheme.errorContainer : null,
      child: InkWell(
        borderRadius: BorderRadius.circular(16),
        onTap: () => context.push(RoutePath.budgets),
        child: Padding(
          padding: const EdgeInsets.fromLTRB(16, 12, 16, 16),
          child: Column(
            crossAxisAlignment: CrossAxisAlignment.start,
            children: [
              Row(
                children: [
                  const Expanded(child: Text('本月支出与预算')),
                  Text(
                    row.level == 'NORMAL'
                        ? (remainingCents >= 0
                              ? '还剩 ${formatYuan(row.remaining)}'
                              : '已超支 ${formatYuan(fromCents(remainingCents.abs()))}')
                        : budgetLevelLabel(row.level),
                    style: theme.textTheme.labelMedium?.copyWith(color: color),
                  ),
                ],
              ),
              const SizedBox(height: 8),
              ClipRRect(
                borderRadius: BorderRadius.circular(4),
                child: LinearProgressIndicator(
                  value: (row.usedPercent / 100).clamp(0.0, 1.0),
                  color: color,
                  minHeight: 8,
                ),
              ),
              const SizedBox(height: 8),
              Text(
                '已用 ${formatYuan(row.used)} / ${formatYuan(row.amount)}'
                '　${row.usedPercent}%',
                style: theme.textTheme.bodySmall?.copyWith(
                  color: theme.colorScheme.onSurfaceVariant,
                  fontFeatures: const [FontFeature.tabularFigures()],
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }
}

