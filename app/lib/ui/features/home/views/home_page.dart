/// §4.6 首页：家庭信息条、记账概要卡、预算进度、待办提醒卡片区、快捷区、最近动态。
///
/// 数据来源是 S9 的 `GET /home/overview` 一次请求（概要 + 预算 + 最近动态）。
/// **待办提醒卡片区不读它**：那份走 `pendingReminderViewModelProvider`，因为「今天已经划掉」是
/// 设备级状态，只有客户端手里那份列表滤得掉——服务端再返一份就会出现「红点 0 条、卡片区还挂着一条」。
///
/// 各区块按模块开关显隐（§3.2、§4.6）：记账关掉就藏概要、预算与 FAB；猫咪/宝宝关掉就不出对应的
/// 快捷入口，最近动态也不会出现它们的条目（后半句由服务端按同一个人的偏好过滤）。
class HomePage extends ConsumerStatefulWidget {
  const HomePage({super.key});

  @override
  ConsumerState<HomePage> createState() => _HomePageState();
}

class _HomePageState extends ConsumerState<HomePage> {
  /// 这一次挂载里引导已经走过一遍了。跨启动的去重靠 `reminder-state.json` 的那个标志，
  /// 这一个只挡「同一次挂载里 initState 之后又重建」的重复。
  bool _guideShown = false;

  @override
  void initState() {
    super.initState();
    // 首帧之后才弹：对话框要一个已经挂好的 Navigator，而 initState 里那一帧还没有
    WidgetsBinding.instance.addPostFrameCallback(
      (_) => _maybeShowBatteryGuide(),
    );
  }

  @override
  Widget build(BuildContext context) {
    final family = ref.watch(familyViewModelProvider);
    final members = ref.watch(homeMembersProvider);
    final overview = ref.watch(homeOverviewProvider);
    final pending =
        ref.watch(pendingReminderViewModelProvider).value ??
        const <PendingReminder>[];
    final finance = ref.watch(moduleEnabledProvider(moduleFinance));
    final cat = ref.watch(moduleEnabledProvider(moduleCat));
    final baby = ref.watch(moduleEnabledProvider(moduleBaby));

    return Scaffold(
      appBar: AppBar(title: Text(family.value?.name ?? '家庭日记')),
      body: family.when(
        loading: () => const Center(child: CircularProgressIndicator()),
        error: (error, _) => _LoadFailure(error: error),
        data: (_) => RefreshIndicator(
          onRefresh: () => _refresh(ref),
          child: ListView(
            padding: const EdgeInsets.only(bottom: 24),
            children: [
              _FamilyBar(
                members: members,
                recordedDays: overview.value?.summary.recordedDays,
              ),
              if (finance) ..._moneyCards(ref, overview),
              if (pending.isNotEmpty) _PendingSection(rows: pending),
              _QuickActions(finance: finance, cat: cat, baby: baby),
              if (overview.value?.recentActivities case final rows?)
                if (rows.isNotEmpty) _RecentSection(rows: rows),
              if (overview.isLoading) const _LoadingRow(),
              if (overview.hasError)
                _FailureRow(
                  error: overview.error,
                  onRetry: () => ref.invalidate(homeOverviewProvider),
                ),
            ],
          ),
        ),
      ),
    );
  }

  /// 记账那三块：概要卡、预算进度、今日自动记账。都没内容就不占位置（§4.6 的「整块不显示」）。
  List<Widget> _moneyCards(WidgetRef ref, AsyncValue<HomeOverview> overview) {
    final data = overview.value;
    if (data == null) {
      return const [];
    }
    final budget = ref.watch(homeFamilyBudgetProvider);
    return [
      _SummaryCard(summary: data.summary),
      if (budget != null)
        _BudgetCard(
          row: budget,
          anyExceeded: ref.watch(homeAnyBudgetExceededProvider),
        ),
      if (data.summary.autoGeneratedToday > 0)
        _AutoGeneratedCard(count: data.summary.autoGeneratedToday),
    ];
  }

  /// 电池优化引导：查一次、弹一次、关掉之后才回写「弹过了」（§4.5.3 的缓解措施①）。
  ///
  /// 三步不能合并：领位若在弹窗之前，首页在两者之间被销毁时（冷启动切 Tab、深链直达）
  /// 引导会被永久烧掉——标志已落下，对话框却再也不会出现。同一次挂载内的重复由 [_guideShown] 防住。
  Future<void> _maybeShowBatteryGuide() async {
    if (_guideShown) {
      return;
    }
    _guideShown = true;
    final shown = await ref
        .read(pendingReminderViewModelProvider.notifier)
        .isBatteryGuideShown();
    if (shown || !mounted) {
      return;
    }
    await showBatteryGuideDialog(
      context,
      // 对话框的契约写死了「异常由调用方兜」：拉不起来就安静躺着，插件静态路径仍在。
      // 与通知设置页同一个理由，不能让平台通道异常裸落到 Zone（S8 审查 m-3 的修复，勿再回退）。
      onOpenSettings: () async {
        try {
          await ref.read(reminderNotifierProvider).openSystemSettings();
        } on Exception catch (e) {
          debugPrint('打开系统设置失败: $e');
        }
      },
    );
    await ref
        .read(pendingReminderViewModelProvider.notifier)
        .markBatteryGuideShown();
  }

  /// 三份数据一起失效，然后等它们真的回来。不等的话手指一抬刷新指示器就消失了，
  /// 数据是过一会儿才补上的，看着像没刷新成功。
  ///
  /// 单个失败不在这里报：各自的 `AsyncError` 已经落在状态里，页面下一帧就会显示它。
  Future<void> _refresh(WidgetRef ref) async {
    ref
      ..invalidate(familyViewModelProvider)
      ..invalidate(homeOverviewProvider)
      ..invalidate(pendingReminderViewModelProvider);
    await Future.wait([
      _quiet(() => ref.read(familyViewModelProvider.future)),
      _quiet(() => ref.read(homeOverviewProvider.future)),
      _quiet(() => ref.read(pendingReminderViewModelProvider.future)),
    ]);
  }
}

Future<Object?> _quiet(Future<Object?> Function() read) async {
  try {
    return await read();
  } on Exception {
    return null;
  }
}

/// §4.6 第 1 条：成员头像列表 + 当月已记录天数。家庭名称在 AppBar 上，这一条里不重复写一遍。
class _FamilyBar extends StatelessWidget {
