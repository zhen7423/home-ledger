/// §4.6 第 4 条：待办提醒的横向卡片列表。空的时候整个区不渲染（调用方已经判过）。
///
/// 顺序直接用后端给的——它按紧急度排好了（逾期 > 3 天内 > 14 天内），前端再排一次就会与
/// 通知栏里那条说法不同。
class _PendingSection extends StatelessWidget {
  const _PendingSection({required this.rows});

  final List<PendingReminder> rows;

  @override
  Widget build(BuildContext context) {
    return Column(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        const SectionHeader(title: '待处理'),
        // 第 34 轮：横向卡片高度统一。SingleChildScrollView + Row 仍比 ListView 合适
        // （待办条数有限，ListView 会把卡拉到整个视口高），但行内各卡按内容自定高度会让
        // 一排卡片参差不齐——IntrinsicHeight + stretch 让每张卡都等于最高那张的高度。
        // 内容仍是顶部对齐：卡只有一种高度，正文短时下端留白由后进不齐的高差承担。
        IntrinsicHeight(
          child: SingleChildScrollView(
            scrollDirection: Axis.horizontal,
            padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 4),
            child: Row(
              crossAxisAlignment: CrossAxisAlignment.stretch,
              children: [for (final row in rows) _PendingCard(row: row)],
            ),
          ),
        ),
      ],
    );
  }
}

class _PendingCard extends StatelessWidget {
  const _PendingCard({required this.row});

  final PendingReminder row;

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final tint = _moduleTint(theme, row.module);

    // 待办卡（问题单：优化）——不再整卡红色警示：纸白底 + 模块图标圈 + 平时字色，
    // 色点只用来「这是哪个模块的事」；阴影由卡片主题统一给出。高度按内容走，
    // 正文不撑满：`body` 短时卡片就短，不留半截空白。
    return Card(
      margin: const EdgeInsets.symmetric(horizontal: 4, vertical: 4),
      child: InkWell(
        borderRadius: BorderRadius.circular(16),
        onTap: () => context.push(row.route),
        child: SizedBox(
          width: 240,
          child: Padding(
            padding: const EdgeInsets.all(12),
            child: Row(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Container(
                  width: 36,
                  height: 36,
                  decoration: BoxDecoration(
                    color: tint.withValues(alpha: 0.1),
                    shape: BoxShape.circle,
                  ),
                  child: Icon(moduleIcon(row.module), size: 20, color: tint),
                ),
                const SizedBox(width: 10),
                Expanded(
                  child: Column(
                    mainAxisSize: MainAxisSize.min,
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        row.title,
                        maxLines: 1,
                        overflow: TextOverflow.ellipsis,
                        style: theme.textTheme.labelLarge?.copyWith(
                          fontWeight: FontWeight.w600,
                        ),
                      ),
                      const SizedBox(height: 4),
                      Text(
                        row.body,
                        maxLines: 3,
                        overflow: TextOverflow.ellipsis,
                        style: theme.textTheme.bodySmall?.copyWith(
                          color: theme.colorScheme.onSurfaceVariant,
                        ),
                      ),
                    ],
                  ),
                ),
              ],
            ),
          ),
        ),
      ),
    );
  }

  /// 待办属于哪个模块，图标圈就用哪个模块的颜色：记账主色橙 / 猫咪 tertiary /
  /// 宝宝 secondary——三个 Tab 的图标本来也是这么着色的（`ModuleKey` 三种模块）。
  Color _moduleTint(ThemeData theme, String module) => switch (module) {
    moduleFinance => theme.colorScheme.primary,
    moduleCat => theme.colorScheme.tertiary,
    moduleBaby => theme.colorScheme.secondary,
    _ => theme.colorScheme.outline,
  };
}

/// §4.6 第 5 条：快捷区。按已启用模块动态显示；一个模块都没启用时整区不占位置。
