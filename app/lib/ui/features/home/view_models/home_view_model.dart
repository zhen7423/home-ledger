/// 首页成员区，数据取自已加载的家庭，不再单独请求 /users/me。
/// 因此首页只标「创建者」不标「我」——认出自己需要 userId，得多发一次请求。
final homeMembersProvider = Provider<List<Member>>((ref) {
  return ref.watch(familyViewModelProvider).value?.members ?? const [];
});

/// §4.6 的首页聚合：概要、预算、最近动态一次拿齐。
///
/// 它替掉了 S4 那两块卡各自发的两次请求（自动记账块查一笔流水、预算块读
/// `/budgets/progress`），数字仍然出自同一批服务端口径，所以是一次纯替换，没有第二套算法。
///
/// **待办提醒不在这里**：那份走 `pendingReminderViewModelProvider`，因为「今天已经划掉」
/// 是设备级状态，只有客户端手里那份列表滤得掉。
final homeOverviewProvider = FutureProvider<HomeOverview>((ref) async {
  if (ref.watch(authViewModelProvider.select((s) => s.status)) !=
      SessionStatus.signedIn) {
    return const HomeOverview(
      summary: HomeSummary(
        monthIncome: '0.00',
        monthExpense: '0.00',
        monthBalance: '0.00',
        recordedDays: 0,
        autoGeneratedToday: 0,
      ),
      budgets: [],
      recentActivities: [],
    );
  }
  return ref.watch(homeRepositoryProvider).overview();
});

/// 聚合里的预算那一份。首页的预算卡要「家庭维度一条进度条 + 任一维度超支就整卡变红」，
/// 所以下面两个 provider 都从它派生，不各自去聚合里翻一遍。
final homeBudgetsProvider = Provider<List<BudgetProgress>>(
  (ref) =>
      ref.watch(homeOverviewProvider).value?.budgets ?? const <BudgetProgress>[],
);

/// 家庭维度那一条预算进度。没设过家庭预算时为 null，首页那块整个不渲染（§4.6 第 3 条）。
final homeFamilyBudgetProvider = Provider<BudgetProgress?>((ref) {
  for (final row in ref.watch(homeBudgetsProvider)) {
    if (row.scope == 'FAMILY') return row;
  }
  return null;
});

/// 任一维度超支就整卡变红（§4.6 第 3 条）。判据取服务端算好的 `level`，
/// 不拿 `usedPercent` 自己比阈值——恰好花完额度时它显示 100 而档位是 EXCEEDED。
final homeAnyBudgetExceededProvider = Provider<bool>(
  (ref) =>
      ref.watch(homeBudgetsProvider).any((row) => row.level == 'EXCEEDED'),
);
