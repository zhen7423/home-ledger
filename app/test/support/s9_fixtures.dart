import 'package:homeledger/data/models/budget_progress.dart';
import 'package:homeledger/data/models/home_overview.dart';
import 'package:homeledger/data/models/module_preference.dart';

/// S9 的首页聚合与模块偏好。两者都是「服务端给形状、前端只渲染」，所以替身也照响应形状造。

/// 一份空的聚合：三个金额都是 0.00、没有预算、没有动态。用例只关心其中一块时，
/// 传自己那一块进来即可。
HomeOverview homeOverview({
  HomeSummary? summary,
  List<BudgetProgress> budgets = const [],
  List<RecentActivity> recentActivities = const [],
}) => HomeOverview(
  summary: summary ?? homeSummary(),
  budgets: budgets,
  recentActivities: recentActivities,
);

HomeSummary homeSummary({
  String monthIncome = '0.00',
  String monthExpense = '0.00',
  String monthBalance = '0.00',
  int recordedDays = 0,
  int autoGeneratedToday = 0,
}) => HomeSummary(
  monthIncome: monthIncome,
  monthExpense: monthExpense,
  monthBalance: monthBalance,
  recordedDays: recordedDays,
  autoGeneratedToday: autoGeneratedToday,
);

RecentActivity recentActivity({
  String module = 'FINANCE',
  String type = 'TRANSACTION',
  String title = '记了一笔支出',
  String summary = '餐饮 · 120.00 元',
  String? actorName = '小明',
  DateTime? occurredAt,
  String route = '/finance/transaction/1',
}) => RecentActivity(
  module: module,
  type: type,
  title: title,
  summary: summary,
  actorName: actorName,
  occurredAt: occurredAt ?? DateTime(2026, 9, 17, 12),
  route: route,
);

/// 三个模块的开关，默认与服务端默认值一致（全开，顺序记账 → 宝宝 → 猫咪，问题单 8）。
List<ModulePreference> modulePreferences({
  bool financeEnabled = true,
  bool catEnabled = true,
  bool babyEnabled = true,
}) => [
  ModulePreference(
    moduleKey: 'FINANCE',
    label: '记账',
    enabled: financeEnabled,
    sortNo: 0,
  ),
  ModulePreference(
    moduleKey: 'BABY',
    label: '宝宝',
    enabled: babyEnabled,
    sortNo: 1,
  ),
  ModulePreference(
    moduleKey: 'CAT',
    label: '猫咪',
    enabled: catEnabled,
    sortNo: 2,
  ),
];
