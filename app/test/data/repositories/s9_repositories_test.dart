import 'package:flutter_test/flutter_test.dart';
import 'package:homeledger/data/repositories/home_repository.dart';
import 'package:homeledger/data/repositories/module_preference_repository.dart';
import 'package:homeledger/data/services/api_client.dart';

import '../../support/fake_http.dart';
import '../../support/fake_token_storage.dart';

/// S9 两条新端点的解析：模块偏好与首页聚合。
///
/// 字段名一个都不能猜——`sortNo` 写成 `sort_no`、`recentActivities` 里的 `occurredAt` 少一个字母，
/// 症状都是界面上那一块默默空着或顺序随机，而单测里只有这一层看得见。
void main() {
  late ScriptedHttp http;

  ApiClient client() => ApiClient(
    storage: FakeTokenStorage(),
    adapter: http,
    origin: 'http://test.local',
  );

  test('模块偏好：路径、顺序与四个字段', () async {
    http = ScriptedHttp(
      (options) => envelope(
        data: [
          {
            'moduleKey': 'CAT',
            'label': '猫咪',
            'enabled': false,
            'sortNo': 0,
          },
          {
            'moduleKey': 'FINANCE',
            'label': '记账',
            'enabled': true,
            'sortNo': 1,
          },
        ],
      ),
    );
    final repository = ModulePreferenceRepository(api: client());

    final rows = await repository.modules();

    expect(http.call.path, '/api/v1/preferences/modules');
    expect(rows.map((row) => row.moduleKey), ['CAT', 'FINANCE']);
    expect(rows.first.enabled, isFalse);
    expect(rows.last.label, '记账');
    expect(rows.last.sortNo, 1);
  });

  test('保存模块：交的是 items 数组，顺序即 Tab 顺序，不带 sortNo', () async {
    http = ScriptedHttp((options) => envelope(data: null));
    final repository = ModulePreferenceRepository(api: client());

    await repository.saveModules(const [
      ModulePreferenceItem(moduleKey: 'BABY', enabled: true),
      ModulePreferenceItem(moduleKey: 'CAT', enabled: false),
    ]);

    expect(http.call.method, 'PUT');
    expect(http.call.body, {
      'items': [
        {'moduleKey': 'BABY', 'enabled': true},
        {'moduleKey': 'CAT', 'enabled': false},
      ],
    });
  });

  test('首页聚合：三个区块的字段与时间串都解得出来', () async {
    http = ScriptedHttp(
      (options) => envelope(
        data: {
          'summary': {
            'monthIncome': '5000.00',
            'monthExpense': '120.00',
            'monthBalance': '4880.00',
            'recordedDays': 3,
            'autoGeneratedToday': 2,
          },
          'budgets': [
            {
              'month': '2026-09',
              'scope': 'FAMILY',
              'amount': '5000.00',
              'used': '120.00',
              'remaining': '4880.00',
              'usedPercent': 2,
              'level': 'NORMAL',
              'remainingDays': 13,
            },
          ],
          'recentActivities': [
            {
              'module': 'CAT',
              'type': 'CAT_DEWORMING',
              'title': '给咪咪做了外驱',
              'summary': '2026-09-17 · 测试用药',
              'actorName': '阿珍',
              'occurredAt': '2026-09-17T08:31:00',
              'route': '/cat/dewormings',
            },
          ],
        },
      ),
    );
    final repository = HomeRepository(api: client());

    final overview = await repository.overview();

    expect(http.call.path, '/api/v1/home/overview');
    expect(overview.summary.monthBalance, '4880.00');
    expect(overview.summary.recordedDays, 3);
    expect(overview.summary.autoGeneratedToday, 2);
    expect(overview.budgets.single.scope, 'FAMILY');
    final activity = overview.recentActivities.single;
    expect(activity.module, 'CAT');
    expect(activity.summary, '2026-09-17 · 测试用药');
    expect(activity.actorName, '阿珍');
    // 后端的时间串不带时区标记，解出来就是本地时间，前端不做换算（§6.1.2 的口径）
    expect(activity.occurredAt, DateTime(2026, 9, 17, 8, 31));
    expect(activity.route, '/cat/dewormings');
  });

  test('聚合里没有动态、预算为空数组时也是合法响应', () async {
    http = ScriptedHttp(
      (options) => envelope(
        data: {
          'summary': {
            'monthIncome': '0.00',
            'monthExpense': '0.00',
            'monthBalance': '0.00',
            'recordedDays': 0,
            'autoGeneratedToday': 0,
          },
          'budgets': [],
          'recentActivities': [],
        },
      ),
    );

    final overview = await HomeRepository(api: client()).overview();

    expect(overview.budgets, isEmpty);
    expect(overview.recentActivities, isEmpty);
  });
}
